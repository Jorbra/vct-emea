export function serverFr(msg) {
  for (const [re, out] of SERVER) {
    const m = re.exec(msg);
    if (!m) continue;
    return typeof out === "function" ? out(m) : msg.replace(re, out);
  }
  return msg;
}

/** tr(key, vars): the text in `lang`, with {name} placeholders filled in. */
export function makeT(lang) {
  const fr = lang === "fr";
  const dict = { fr: FR, tr: TR, ar: AR }[lang];
  const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`)) : s);
  const tr = (key, vars) => fill(dict && dict[key] !== undefined ? dict[key] : key, vars);
  tr.lang = lang;
  tr.server = (msg) => (fr ? serverFr(msg) : msg);
  return tr;
}
